/**
 * Public posts (v5, docs/design/discover-posts.html): a signed-in user posts
 * a question for everyone, and up to five relevant Rees answer it on their
 * own. What the browser and the server agree on; the server side is
 * lib/services/posts.ts.
 *
 * Billing (the user's choice, 2026-11-19): posting costs nothing; each
 * answer is charged on its own, to the post's author.
 * - A free Ree of someone else answers at once and costs the base fee of a
 *   question (`QUERY_BASE_FEE`), to the platform; at most `POST_MAX_ANSWERS`
 *   answer, so the automatic answers cost at most `POST_MAX_ANSWERS` base
 *   fees. One the balance cannot cover waits for the author to agree.
 * - A paid Ree answers only once the author agrees (the user's rule), at the
 *   base fee plus its query fee, which goes to its owner.
 * - Nothing is charged for an answer not given, for the author's own Rees,
 *   or on RE0's example posts.
 */
import type { CitationSnapshot } from '@/lib/domain/answer';
import type { SynthesisSource } from '@/lib/domain/synthesis';

/** Posts a user may publish a day: a ceiling against scripts, not a price. */
export const POST_DAILY_LIMIT = 30;
/** The round-table summary of a post's answers, generated by its author for everyone. */
export const POST_SUMMARY_FEE = 30;
/**
 * A stale summary is rewritten free at most this many times per post, and
 * only when the author's own Rees had no part in it going stale (an answer
 * of theirs hidden or their Ree made private); otherwise the rewrite costs
 * `POST_SUMMARY_FEE` like the first one.
 */
export const POST_SUMMARY_FREE_REWRITES = 2;
/** Rees that answer one post, the mentioned one included. */
export const POST_MAX_ANSWERS = 5;
/** Candidates the search hands over before the threshold. */
export const POST_CANDIDATES = 10;
/** The best passage of a Ree must be at least this close to the question for it to answer (P4). */
export const POST_MIN_SIMILARITY = 0.45;
export const POST_QUESTION_MAX = 300;
export const POST_DETAIL_MAX = 2000;
/** A feed page. */
export const POST_PAGE_SIZE = 15;
/** An answer longer than this is cut in a feed; the post page shows it whole. */
export const POST_PREVIEW_CHARS = 280;
/** A post still `answering` after this belongs to no live run: the cron finishes it with what it has. */
export const POST_ANSWERING_STALE_MS = 10 * 60_000;
/** The same text from the same author within this long is the same post (a double submit), published and held once. */
export const POST_DUPLICATE_WINDOW_MS = 60_000;
/** Quotes of one post within this long fold into one unread notice for its author. */
export const POST_QUOTE_NOTICE_MERGE_MS = 60 * 60_000;
/** One quoter tells one author at most once in this long. */
export const POST_QUOTE_NOTICE_QUOTER_MS = 24 * 3_600_000;
/** Distinct reporters that hide a post's question until an administrator looks (the answers' rule, #158). */
export const POST_REPORT_THRESHOLD = 3;
/** The posts sweep (`/api/cron/posts`, every 5 minutes): how long it starts new work, and how many posts it answers at once. */
export const POST_SWEEP_BUDGET_MS = 200_000;
export const POST_SWEEP_CONCURRENCY = 4;
/** How many times the author may agree to one request in all: a failed answer can be tried again once; one that found no answer cannot. */
export const POST_PAID_AGREE_MAX = 2;
/** A paid answer agreed to but still running after this belongs to no live run: its holds are given back. */
export const POST_PAID_ANSWER_STALE_MS = 10 * 60_000;
/** A published post not yet started after this (the request's background work died): the cron starts it. */
export const POST_WAITING_STALE_MS = 2 * 60_000;

export const POST_SOURCES = ['post', 'anonymous', 'share', 'conversation', 'seed'] as const;
export type PostSource = (typeof POST_SOURCES)[number];
export const POST_STATUSES = ['pending', 'published', 'rejected', 'hidden'] as const;
export type PostStatus = (typeof POST_STATUSES)[number];
export const POST_ANSWER_STATES = ['waiting', 'answering', 'done'] as const;
export type PostAnswerState = (typeof POST_ANSWER_STATES)[number];
/** `awaiting`: a paid Ree waiting for the post's author to agree; `declined`: the author said no. Neither is ever shown to anyone else. */
export const ANSWER_STATES = ['queued', 'answering', 'answered', 'no_answer', 'failed', 'awaiting', 'declined'] as const;
export type AnswerState = (typeof ANSWER_STATES)[number];
export const ANSWER_HIDERS = ['owner', 'admin', 'reports'] as const;
export type AnswerHider = (typeof ANSWER_HIDERS)[number];

export const FEED_TABS = ['for_you', 'latest', 'unanswered'] as const;
export type FeedTab = (typeof FEED_TABS)[number];

export function feedTabOf(value: unknown): FeedTab {
  return FEED_TABS.includes(value as FeedTab) ? (value as FeedTab) : 'for_you';
}

/** What a reader sees of who posted: a name, "一位用户" (anonymous or from a conversation), a visitor, or RE0's example. */
export type PostAuthor =
  | { kind: 'user'; name: string; avatar: string | null; mine: boolean }
  | { kind: 'hidden'; mine: boolean }
  | { kind: 'visitor' }
  | { kind: 'example' };

export interface PostAnswerView {
  id: string;
  reeId: string;
  reeSlug: string;
  reeName: string;
  reeAvatar: string | null;
  reeColor: string;
  official: boolean;
  similarity: number | null;
  state: AnswerState;
  text: string;
  truncated: boolean;
  citations: CitationSnapshot[];
  helpful: number;
  voted: boolean;
  pinned: boolean;
  /** A paid Ree's answer the post's author agreed to pay for. */
  paid: boolean;
}

/** A paid Ree waiting for the post's author to agree (only the author sees it). */
export interface PaidRequestView {
  id: string;
  reeId: string;
  reeSlug: string;
  reeName: string;
  reeAvatar: string | null;
  reeColor: string;
  ownerName: string;
  similarity: number | null;
  mentioned: boolean;
  /** What agreeing costs now: the base fee and the Ree's query fee. */
  price: number;
  /**
   * `answering` once agreed, until the answer is written. Agreed but not
   * answered, everything given back: `refunded` (it failed; the author may
   * agree again), `no_answer` (the Ree had nothing; no retry) or `exhausted`
   * (failed again after `POST_PAID_AGREE_MAX` tries).
   */
  state: 'awaiting' | 'answering' | 'refunded' | 'no_answer' | 'exhausted';
}

export interface PostSummaryView {
  state: 'running' | 'done';
  content: string;
  sources: SynthesisSource[];
}

/**
 * What a quoting post shows of what it quotes ("引用提问"), one level only:
 * the quoted post's own quote is not shown. Once the quoted post or answer
 * can no longer be seen -- trashed, taken down, purged, its Ree private --
 * only `available: false` is left: no id, no text.
 */
export type PostQuote =
  | { kind: 'post' | 'answer'; available: false }
  | {
      kind: 'post' | 'answer';
      available: true;
      postId: string;
      question: string;
      author: PostAuthor;
      createdAt: string;
      answer: { id: string; reeName: string; reeSlug: string; reeAvatar: string | null; reeColor: string; text: string } | null;
    };

/** How much of a quoted post or answer a card shows. */
export const POST_QUOTE_PREVIEW_CHARS = 160;

export interface PostView {
  id: string;
  question: string;
  detail: string;
  lang: 'zh' | 'en';
  category: string | null;
  author: PostAuthor;
  status: PostStatus;
  answerState: PostAnswerState;
  /** Answers given (shown ones). */
  answered: number;
  candidates: number;
  /** Candidates that were not close enough to answer. */
  skipped: number;
  helpful: number;
  saved: boolean;
  createdAt: string;
  answers: PostAnswerView[];
  summary: PostSummaryView | null;
  /** A summary was written but an answer it drew on is no longer shown: it is not shown, and its author may write it again free. */
  summaryStale: boolean;
  /** For the author of a stale summary: rewriting it is free (`POST_SUMMARY_FREE_REWRITES`, and not stale through their own Rees). */
  summaryRewriteFree: boolean;
  /** Why a published post was taken down (its author still sees it). */
  hiddenBy: 'admin' | 'reports' | null;
  /** What this post quotes ("引用提问"), when it quotes something. */
  quote: PostQuote | null;
  /** Visible posts that quote this one. */
  quotes: number;
  /** The author's follow-up conversations from this post ("继续问"), only for the author. */
  followUps: { id: string; title: string; reeName: string | null }[];
  /** Rees waiting for the author to agree (paid ones, and free ones the balance could not cover), only for the author on the post's page. */
  paidRequests: PaidRequestView[];
  /** What the answers cost the author so far, only for the author on the post's page; null otherwise. */
  spent: number | null;
  deleted: boolean;
}

export interface PostPage {
  items: PostView[];
  next: string | null;
}

/** The UTC day a post counts against the daily limit, like the anonymous rounds. */
export function postDay(now: Date): string {
  return now.toISOString().slice(0, 10);
}

/** `@Name` at the start or after a space, for the mention a Ree page prefills. Never part of the stored question. */
export function stripMention(question: string, name: string | null): string {
  if (!name) return question.trim();
  return question.replace(new RegExp(`(^|\\s)@${name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}(?=\\s|$)`, 'g'), ' ').replace(/\s+/g, ' ').trim();
}

/** Whether the question fits: something to ask, and not too long. */
export function postInputError(question: string, detail: string): 'empty' | 'too_long' | null {
  if (!question.trim()) return 'empty';
  if (question.trim().length > POST_QUESTION_MAX || detail.trim().length > POST_DETAIL_MAX) return 'too_long';
  return null;
}
